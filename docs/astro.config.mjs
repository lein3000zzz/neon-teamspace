// @ts-check
import { unified } from '@astrojs/markdown-remark'
import starlight from '@astrojs/starlight'
import { defineConfig, passthroughImageService } from 'astro/config'
import rehypeMermaid from 'rehype-mermaid'
import starlightLinksValidator from 'starlight-links-validator'
import starlightOpenAPI, { createOpenAPISidebarGroup } from 'starlight-openapi'

import { thirdPartyNotices } from './scripts/lib/notices.ts'

const apiReference = createOpenAPISidebarGroup()

// Diagrams in the Nothing palette: white boxes, black 1px lines, system sans. custom.css
// inverts them in dark mode. Labels are SVG text, not HTML, so the page's styles cannot
// change their size after the build measured them.
/** @type {import('mermaid').MermaidConfig} */
const mermaidConfig = {
  theme: 'base',
  htmlLabels: false,
  flowchart: { curve: 'linear' },
  themeVariables: {
    fontFamily: 'ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, sans-serif',
    background: '#ffffff',
    primaryColor: '#ffffff',
    primaryTextColor: '#000000',
    primaryBorderColor: '#000000',
    secondaryColor: '#ffffff',
    tertiaryColor: '#ffffff',
    lineColor: '#000000',
    clusterBkg: '#ffffff',
    clusterBorder: '#d8d8d8',
    edgeLabelBackground: '#ffffff',
    noteBkgColor: '#ffffff',
    noteBorderColor: '#d8d8d8',
  },
}

// The docs are served at /docs, on the same origin as the app and the API.
export default defineConfig({
  base: '/docs',
  // Images are served as they are. Astro's default service loads sharp, whose libvips binary
  // is LGPL, and the docs have no images that need resizing.
  image: { service: passthroughImageService() },
  markdown: {
    // Diagrams are drawn when the docs build, as inline SVG: no script on the page, and the
    // theme's colours over them (custom.css), light and dark.
    processor: unified({
      rehypePlugins: [[rehypeMermaid, { strategy: 'inline-svg', mermaidConfig }]],
    }),
  },
  integrations: [
    // THIRD_PARTY_NOTICES.txt beside the pages: the licenses of the packages they ship.
    thirdPartyNotices(),
    starlight({
      title: 'Neon Teamspace',
      description:
        'A self-hosted team workspace: pages, databases and boards, edited together in real time, with agents as teammates.',
      logo: {
        light: './src/assets/logo-light.svg',
        dark: './src/assets/logo-dark.svg',
      },
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/lein3000zzz/neon-teamspace' }],
      customCss: ['./src/styles/custom.css'],
      expressiveCode: {
        styleOverrides: {
          borderRadius: '0',
          borderColor: 'var(--sl-color-hairline)',
          codeFontFamily: 'var(--__sl-font-mono)',
          uiFontFamily: 'var(--__sl-font)',
          frames: { shadowColor: 'transparent' },
        },
      },
      plugins: [
        starlightOpenAPI([
          {
            base: 'reference/api',
            schema: '../api/openapi.json',
            sidebar: { label: 'API', group: apiReference, collapsed: false },
          },
        ]),
        // Every internal link and anchor must resolve; checked on each build.
        starlightLinksValidator({
          exclude: [
            // Generated by starlight-openapi as routes, outside the content the validator reads.
            '/docs/reference/api/**',
            // The app, beside the docs on the same origin.
            '/',
          ],
        }),
      ],
      sidebar: [
        {
          label: 'Guides',
          items: [
            'guides/introduction',
            'guides/concepts',
            'guides/signing-in',
            'guides/accounts',
            'guides/workspaces',
            'guides/workspace-rules',
            'guides/editing-pages',
            'guides/pages',
          ],
        },
        {
          label: 'Workspace settings',
          items: [
            'workspace-settings/general',
            'workspace-settings/members',
            'workspace-settings/teamspaces',
          ],
        },
        {
          label: 'Administration',
          items: ['admin/users', 'admin/invites', 'admin/workspaces', 'admin/settings'],
        },
        {
          label: 'Self-hosting',
          items: [
            'self-hosting/install',
            'self-hosting/configuration',
            'self-hosting/mail',
            'self-hosting/observability',
          ],
        },
        {
          label: 'Reference',
          items: ['reference/settings', 'reference/permissions', apiReference],
        },
        {
          label: 'Architecture',
          items: [
            'architecture/overview',
            'architecture/data',
            'architecture/documents',
            'architecture/security',
            'architecture/observability',
            'architecture/web',
            'architecture/decisions',
          ],
        },
      ],
    }),
  ],
})
