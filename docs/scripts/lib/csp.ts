// The docs' Content-Security-Policy, worked out from the built pages.
//
// The app allows scripts from its own origin only. Starlight puts a few small scripts
// inline (the theme, the sidebar, the table of contents), so the docs allow exactly those,
// by hash, and nothing else inline. Search (Pagefind) compiles WebAssembly, which needs
// 'wasm-unsafe-eval'; that does not allow eval() of JavaScript.
import { createHash } from 'node:crypto'

/** What a page needs from the policy, and what no policy short of unsafe-inline allows. */
export interface PageScripts {
  /** Source expressions for the page's inline scripts, such as `'sha256-…'`. */
  hashes: Set<string>
  /** Elements with an event handler attribute, such as `<button onclick>`. */
  handlers: string[]
}

export function scanPage(html: string): PageScripts {
  const hashes = new Set<string>()
  const handlers: string[] = []
  let inline: string[] | undefined

  new HTMLRewriter()
    .on('script', {
      element(script) {
        // A script with src comes from the docs' own files, which 'self' covers.
        if (script.hasAttribute('src')) return

        const chunks: string[] = []
        inline = chunks
        script.onEndTag(() => {
          hashes.add(sourceHash(chunks.join('')))
          inline = undefined
        })
      },
      text(chunk) {
        inline?.push(chunk.text)
      },
    })
    .on('*', {
      element(element) {
        for (const [name] of element.attributes) {
          if (name.startsWith('on')) handlers.push(`<${element.tagName} ${name}>`)
        }
      },
    })
    .transform(html)

  return { hashes, handlers }
}

/** A CSP source expression allowing an inline script with exactly this text. */
export function sourceHash(script: string): string {
  return `'sha256-${createHash('sha256').update(script).digest('base64')}'`
}

export function policy(hashes: Iterable<string>): string {
  return [
    "default-src 'self'",
    ["script-src 'self' 'wasm-unsafe-eval'", ...[...hashes].sort()].join(' '),
    // Starlight and the diagrams' SVG carry inline styles.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ')
}

/** The snippet the web image's Caddyfile imports where it serves /docs. */
export function caddySnippet(policy: string): string {
  return (
    '# Generated by docs/scripts/csp.ts from the built pages. Do not edit.\n' +
    `header Content-Security-Policy "${policy}"\n`
  )
}
