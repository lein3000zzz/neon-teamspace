import { describe, expect, test } from 'bun:test'

import { caddySnippet, policy, scanPage, sourceHash } from './csp'

describe('sourceHash', () => {
  test('matches the example of the CSP specification', () => {
    expect(sourceHash("alert('Hello, world.');")).toBe("'sha256-qznLcsROx4GACP2dm0UCKCzCG+HiZ1guq6ZZDob/Tng='")
  })
})

describe('scanPage', () => {
  test('hashes each inline script by its exact text', () => {
    const { hashes } = scanPage(
      '<html><head><script>let a = 1</script></head><body><script type="module">  b()\n</script></body></html>',
    )

    expect([...hashes].sort()).toEqual([sourceHash('let a = 1'), sourceHash('  b()\n')].sort())
  })

  test('leaves out scripts loaded from a file', () => {
    const { hashes } = scanPage('<script type="module" src="/docs/_astro/page.js"></script>')

    expect(hashes.size).toBe(0)
  })

  test('hashes an empty inline script', () => {
    const { hashes } = scanPage('<script></script>')

    expect([...hashes]).toEqual(["'sha256-47DEQpj8HBSa+/TImW+5JCeuQeRkm5NMpJWZG3hSuFU='"])
  })

  test('keeps markup inside a script as script text', () => {
    const body = 'document.body.innerHTML = "<b>x</b>"'
    const { hashes } = scanPage(`<script>${body}</script>`)

    expect([...hashes]).toEqual([sourceHash(body)])
  })

  test('counts one script once however often it appears', () => {
    const { hashes } = scanPage('<script>x()</script><script>x()</script>')

    expect(hashes.size).toBe(1)
  })

  test('reports event handler attributes in any letter case, which no hash allows', () => {
    const { handlers } = scanPage('<button onclick="go()">Go</button><svg><g onLoad="x()"></g></svg><a href="/">ok</a>')

    expect(handlers).toEqual(['<button onclick>', '<g onload>'])
  })

  test('does not mistake text or attribute values for handlers', () => {
    const { handlers } = scanPage('<p title="once onclick=1">onclick="x()"</p><code>onload=</code>')

    expect(handlers).toEqual([])
  })
})

describe('policy', () => {
  test('allows the given scripts by hash, sorted, and nothing else inline', () => {
    const text = policy(["'sha256-b'", "'sha256-a'"])

    expect(text).toContain("script-src 'self' 'wasm-unsafe-eval' 'sha256-a' 'sha256-b';")
    expect(text).toStartWith("default-src 'self'; ")
    expect(text).toContain("object-src 'none'")
    expect(text).toContain("frame-ancestors 'none'")
    expect(text).not.toContain("'unsafe-eval'")
    expect(text).not.toMatch(/script-src[^;]*'unsafe-inline'/)
  })

  test('still allows the docs own files with no inline scripts', () => {
    expect(policy([])).toContain("script-src 'self' 'wasm-unsafe-eval';")
  })
})

describe('caddySnippet', () => {
  test('is a header directive with the policy in double quotes', () => {
    const snippet = caddySnippet("default-src 'self'")

    expect(snippet).toEndWith(`header Content-Security-Policy "default-src 'self'"\n`)
    expect(snippet.split('\n')[0]).toStartWith('# Generated by docs/scripts/csp.ts')
  })
})
